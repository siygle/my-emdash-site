#!/usr/bin/env node
/**
 * Regenerates the Omarchy palettes from basecamp/omarchy's themes/<name>/colors.toml.
 *
 *   node scripts/sync-palettes.mjs            # latest omarchy default branch
 *   node scripts/sync-palettes.mjs <git-ref>  # pin a tag/commit
 *
 * Writes:
 *   src/styles/palettes.css  -- one [data-palette="<id>"] block of --om-* variables per theme
 *   src/palettes.ts          -- palette list (id, name, mode, swatches) for the picker
 *
 * Uses only Node built-ins (fetch, fs). Set GITHUB_TOKEN to avoid API rate limits.
 */
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const REPO = "basecamp/omarchy";
const refArg = process.argv[2];
const root = new URL("..", import.meta.url);

const headers = { "User-Agent": "my-emdash-site" };
if (process.env.GITHUB_TOKEN) headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`;

async function getJson(url) {
	const res = await fetch(url, { headers });
	if (!res.ok) throw new Error(`${res.status} ${res.statusText} for ${url}`);
	return res.json();
}

async function getText(url) {
	const res = await fetch(url, { headers });
	if (!res.ok) throw new Error(`${res.status} ${res.statusText} for ${url}`);
	return res.text();
}

/** Omarchy colors.toml files are flat `key = "value"` pairs. */
function parseFlatToml(source) {
	const out = {};
	for (const line of source.split("\n")) {
		const match = line.match(/^\s*([A-Za-z0-9_]+)\s*=\s*"([^"]*)"\s*(?:#.*)?$/);
		if (match) out[match[1]] = match[2].trim();
	}
	return out;
}

/** Hyprland colors: rgba(rrggbbaa) / rgb(rrggbb) -> #rrggbb[aa]; hex passes through. */
function toCssColor(value) {
	const match = value.match(/^rgba?\(([0-9a-fA-F]{6,8})\)$/);
	return match ? `#${match[1].toLowerCase()}` : value.toLowerCase();
}

/** "rgba(..) rgba(..) 45deg" -> linear-gradient(45deg, .., ..). One color -> solid. */
function toCssGradient(value) {
	const parts = value.trim().split(/\s+/);
	const angle = parts.at(-1)?.endsWith("deg") ? parts.pop() : "45deg";
	const colors = parts.map(toCssColor);
	if (colors.length === 1) colors.push(colors[0]);
	return `linear-gradient(${angle}, ${colors.join(", ")})`;
}

function titleCase(id) {
	return id
		.split("-")
		.map((word) => word[0].toUpperCase() + word.slice(1))
		.join(" ");
}

const COLOR_KEYS = [
	"accent", "selection", "muted",
	"background", "dark_background", "darker_background", "lighter_background",
	"foreground", "dark_foreground", "light_foreground", "bright_foreground",
	"red", "green", "yellow", "orange", "blue", "magenta", "cyan", "brown",
	"bright_red", "bright_green", "bright_yellow", "bright_blue", "bright_magenta", "bright_cyan",
];

const ref = refArg ?? (await getJson(`https://api.github.com/repos/${REPO}`)).default_branch;
const commit = await getJson(`https://api.github.com/repos/${REPO}/commits/${ref}`);
const sha = commit.sha;
const entries = await getJson(`https://api.github.com/repos/${REPO}/contents/themes?ref=${sha}`);
const ids = entries.filter((entry) => entry.type === "dir").map((entry) => entry.name).sort();

const palettes = [];
for (const id of ids) {
	let toml;
	try {
		toml = await getText(`https://raw.githubusercontent.com/${REPO}/${sha}/themes/${id}/colors.toml`);
	} catch {
		console.warn(`skip ${id}: no colors.toml`);
		continue;
	}
	const colors = parseFlatToml(toml);
	if (!colors.background || !colors.foreground || !colors.accent) {
		console.warn(`skip ${id}: missing background/foreground/accent`);
		continue;
	}
	palettes.push({
		id,
		name: titleCase(id),
		mode: colors.mode === "light" ? "light" : "dark",
		colors,
	});
}

const css = [
	`/*`,
	` * GENERATED by scripts/sync-palettes.mjs from ${REPO}@${sha.slice(0, 7)}.`,
	` * Do not edit by hand -- rerun the script. Raw Omarchy colors are exposed as`,
	` * --om-*; src/styles/tokens.css maps them onto the site's design tokens.`,
	` */`,
	``,
];
for (const { id, mode, colors } of palettes) {
	css.push(`:root[data-palette="${id}"] {`);
	css.push(`\tcolor-scheme: ${mode};`);
	for (const key of COLOR_KEYS) {
		if (colors[key]) css.push(`\t--om-${key.replaceAll("_", "-")}: ${colors[key].toLowerCase()};`);
	}
	css.push(`\t--om-active-border: ${toCssGradient(colors.hyprland_active_border ?? colors.accent)};`);
	css.push(`\t--om-inactive-border: ${toCssColor(colors.hyprland_inactive_border ?? colors.muted ?? colors.selection)};`);
	css.push(`}`, ``);
}

const ts = [
	`// GENERATED by scripts/sync-palettes.mjs from ${REPO}@${sha.slice(0, 7)}. Do not edit by hand.`,
	``,
	`export interface Palette {`,
	`\tid: string;`,
	`\tname: string;`,
	`\tmode: "light" | "dark";`,
	`\t/** [background, foreground, accent] for the picker swatch */`,
	`\tswatch: [string, string, string];`,
	`}`,
	``,
	`export const palettes: Palette[] = ${JSON.stringify(
		palettes
			.map(({ id, name, mode, colors }) => ({
				id,
				name,
				mode,
				swatch: [colors.background, colors.foreground, colors.accent].map((c) => c.toLowerCase()),
			}))
			// light themes first, then alphabetical
			.sort((a, b) => (a.mode === b.mode ? a.id.localeCompare(b.id) : a.mode === "light" ? -1 : 1)),
		null,
		"\t",
	)};`,
	``,
	`export const paletteIds = new Set(palettes.map((palette) => palette.id));`,
	``,
];

await writeFile(new URL("src/styles/palettes.css", root), css.join("\n"));
await writeFile(new URL("src/palettes.ts", root), ts.join("\n"));
console.log(
	`Wrote ${palettes.length} palettes from ${REPO}@${sha.slice(0, 7)} to`,
	fileURLToPath(new URL("src/", root)),
);
